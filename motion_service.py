
import os
import time
import threading
import requests
from dotenv import load_dotenv
from datetime import datetime
from database import insert_motion_batch

load_dotenv()


class MotionService:
    def __init__(self):
        self.url = os.getenv("MOTION_SENSOR_URL", "").strip()

        if not self.url:
            raise ValueError(
                "MOTION_SENSOR_URL is missing from the .env file."
            )

        self.motion_detected = False
        self.sensor_online = False
        self.trigger_count = 0
        # Counter baseline prevents adding triggers that occurred before
        # Flask started; drops to zero after an ESP32 reboot.
        self.last_seen_count = None

        self.running = True
        self.lock = threading.Lock()

        self.thread = threading.Thread(
            target=self._poll_sensor,
            daemon=True
        )
        self.thread.start()

    def _poll_sensor(self):
        while self.running:
            try:
                response = requests.get(
                    self.url,
                    timeout=(1, 2)
                )
                response.raise_for_status()

                data = response.json()

                # Read the values generated by the ESP32-CAM.
                motion = not data["motion"]
                count = data["trigger_count"]

                if not isinstance(motion, bool):
                    raise ValueError("Invalid motion reading")

                if type(count) is not int or count < 0:
                    raise ValueError("Invalid trigger count")

                if self.last_seen_count is None or count < self.last_seen_count:
                    # Initial connection or counter reset after ESP32 restart.
                    # Existing count is a baseline, not newly recorded events.
                    self.last_seen_count = count
                elif count > self.last_seen_count:
                    new_triggers = count - self.last_seen_count
                    insert_motion_batch(
                        datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
                        new_triggers
                    )
                    self.last_seen_count = count
                    print(f"RCWL: {new_triggers} new trigger(s) recorded")

                with self.lock:
                    self.motion_detected = motion
                    self.trigger_count = count
                    self.sensor_online = True

            except (
                requests.RequestException,
                ValueError,
                KeyError,
                OSError
            ) as error:
                with self.lock:
                    self.sensor_online = False
                    self.motion_detected = False

                print("RCWL sensor connection error:", error)

            time.sleep(2)

    def get_status(self):
        with self.lock:
            return {
                "sensor_online": self.sensor_online,
                "motion_detected": self.motion_detected,
                "trigger_count": self.trigger_count
            }

    def stop(self):
        self.running = False
        self.thread.join(timeout=3)
